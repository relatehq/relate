"""Rebuild tables.md and the charts from the retained before/after archives.

uv run tests/performance/analytical-properties/measurements/object-lookup-2026-10-23/analyze.py
"""
import gzip
import json
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

DEST = Path(__file__).resolve().parent
RUNS = ["small", "capacity", "postgres-store"]
SCENARIOS = ["objects", "enrichment", "ranking"]


def load(side, name):
    return json.loads(gzip.decompress((DEST / f"{side}-{name}.json.gz").read_bytes()))


def nearest_rank(values, q):
    values = sorted(values)
    return values[math.ceil(len(values) * q) - 1]


def warm(workload, scenario):
    samples = [
        s
        for s in workload["samples"]
        if s["mode"] == "relate" and s["phase"] == "warm" and s["scenario"] == scenario
    ]
    assert samples and all(s["status"] == "ok" for s in samples)
    return samples


def key(workload):
    c = workload["config"]
    return (c["objectStore"], c["customers"], c["events"])


def rows():
    for name in RUNS:
        before, after = load("before", name), load("after", name)
        paired = {key(w): w for w in after["workloads"]}
        for w in before["workloads"]:
            a = paired[key(w)]
            for scenario in SCENARIOS:
                b_samples, a_samples = warm(w, scenario), warm(a, scenario)
                b = [s["durationMs"] for s in b_samples]
                f = [s["durationMs"] for s in a_samples]
                counters = {
                    k: (b_samples[0]["counters"][k], a_samples[0]["counters"][k])
                    for k in ["membershipScans", "objectLoads", "computedSlots"]
                }
                yield {
                    "store": key(w)[0],
                    "customers": key(w)[1],
                    "events": key(w)[2],
                    "scenario": scenario,
                    "n": (len(b), len(f)),
                    "before": (nearest_rank(b, 0.5), min(b), max(b)),
                    "after": (nearest_rank(f, 0.5), min(f), max(f)),
                    "counters": counters,
                }


def fmt(ms):
    return f"{ms:,.1f}"


def tables(data):
    out = [
        "# Before/after tables",
        "",
        "Generated by `analyze.py` from the retained archives. Warm samples only;",
        "median is nearest-rank. Ranges are min–max of warm samples. PostgreSQL",
        "analytical backend, activity capture disabled, cached freshness.",
        "",
        "| Object store | Customers | Events | Scenario | Samples (before/after) | Before median ms | Before range | After median ms | After range | Speedup |",
        "| --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for r in data:
        (b, bl, bh), (a, al, ah) = r["before"], r["after"]
        out.append(
            f"| {r['store']} | {r['customers']:,} | {r['events']:,} | {r['scenario']} | {r['n'][0]}/{r['n'][1]} | {fmt(b)} | {fmt(bl)}–{fmt(bh)} | {fmt(a)} | {fmt(al)}–{fmt(ah)} | {b / a:.2f}× |"
        )
    out += [
        "",
        "Actual counters from the first warm sample. Full-scope ranking does the",
        "same work before and after. Page scenarios stop after enough authorized",
        "matches; object IDs are random per run, so their scan/load counts vary.",
        "",
        "| Object store | Customers | Events | Scenario | Membership scans (before/after) | Object loads (before/after) | Computed slots |",
        "| --- | ---: | ---: | --- | ---: | ---: | ---: |",
    ]
    for r in data:
        c = r["counters"]
        if r["scenario"] == "ranking":
            assert all(x == y for x, y in c.values()), r
        out.append(
            f"| {r['store']} | {r['customers']:,} | {r['events']:,} | {r['scenario']} | {c['membershipScans'][0]:,}/{c['membershipScans'][1]:,} | {c['objectLoads'][0]:,}/{c['objectLoads'][1]:,} | {c['computedSlots'][1]:,} |"
        )
    out += ["", "## CPU profiles (one profiled warm ranking request each)", ""]
    for store in ["memory", "postgres"]:
        suffix = "" if store == "memory" else "-postgres-store"
        out += [
            f"### {store} object store",
            "",
            "| Owner (self time) | Before ms | After ms |",
            "| --- | ---: | ---: |",
        ]
        prof = {
            side: json.loads(
                gzip.decompress(
                    (DEST / f"{side}-profile{suffix}.json.gz").read_bytes()
                )
            )
            for side in ["before", "after"]
        }
        owners = {
            side: {o["owner"]: o["selfMs"] for o in prof[side]["owners"]}
            for side in prof
        }
        names = sorted(
            set(list(owners["before"])[:10]) | set(list(owners["after"])[:10]),
            key=lambda n: -max(owners["before"].get(n, 0), owners["after"].get(n, 0)),
        )
        for n in names:
            out.append(
                f"| `{n}` | {fmt(owners['before'].get(n, 0))} | {fmt(owners['after'].get(n, 0))} |"
            )
        out.append(
            f"| **Profiled request elapsed** | {fmt(prof['before']['elapsedMs'])} | {fmt(prof['after']['elapsedMs'])} |"
        )
        out += ["", "Top frames after the change:", ""]
        out += ["| Function | Location | Self ms |", "| --- | --- | ---: |"]
        for f in prof["after"]["frames"][:15]:
            loc = f["url"].replace("file://<repo>/", "") or "(native)"
            out.append(f"| `{f['functionName']}` | `{loc}:{f['lineNumber']}` | {fmt(f['selfMs'])} |")
        out.append("")
    (DEST / "tables.md").write_text("\n".join(out) + "\n")


def chart(data):
    ranking = [r for r in data if r["scenario"] == "ranking"]
    labels = [
        f"{r['customers']:,} / {r['events']:,}\n{r['store']} store" for r in ranking
    ]
    fig, ax = plt.subplots(figsize=(10, 4.8))
    x = range(len(ranking))
    w = 0.38
    for i, (side, color) in enumerate([("before", "#9aa5b1"), ("after", "#2f6fdf")]):
        med = [r[side][0] for r in ranking]
        lo = [r[side][0] - r[side][1] for r in ranking]
        hi = [r[side][2] - r[side][0] for r in ranking]
        bars = ax.bar(
            [p + (i - 0.5) * w for p in x],
            med,
            w,
            label=side,
            color=color,
            yerr=[lo, hi],
            capsize=3,
        )
        for b, m in zip(bars, med):
            ax.annotate(
                f"{m:,.0f}",
                (b.get_x() + b.get_width() / 2, m),
                ha="center",
                va="bottom",
                fontsize=8,
                xytext=(0, 3),
                textcoords="offset points",
            )
    ax.set_xticks(list(x), labels, fontsize=8)
    ax.set_yscale("log")
    ax.set_ylabel("Warm median ms (log); whiskers min–max")
    ax.set_title("Full public ranking request: customers / events, before and after")
    ax.legend()
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(DEST / "ranking.png", dpi=150)


if __name__ == "__main__":
    data = list(rows())
    tables(data)
    chart(data)
